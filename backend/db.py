def _sql(sql: str) -> str:
    return sql.replace("?", "%s")


def _executemany(conn, sql: str, params) -> None:
    with conn.cursor() as cur:
        cur.executemany(sql, params)


def connect():
    import psycopg

    settings = get_postgres_settings()
    if not settings["dbname"] or not settings["user"]:
        raise RuntimeError("Set POSTGRES_DB and POSTGRES_USER in the environment before starting the app.")
    conn = psycopg.connect(**settings, row_factory=dict_row)
    conn.execute("SET search_path TO spl_portal, public")
    return conn


def rows(sql: str, params: tuple = ()) -> list[dict]:
    conn = connect()
    try:
        return [dict(row) for row in conn.execute(_sql(sql), params).fetchall()]
    finally:
        conn.close()


def one(sql: str, params: tuple = ()) -> dict | None:
    found = rows(sql, params)
    return found[0] if found else None


def execute(sql: str, params: tuple = ()) -> None:
    conn = connect()
    try:
        conn.execute(_sql(sql), params)
        conn.commit()
    finally:
        conn.close()


def init_db() -> None:
    from backend.academy import init_academy

    conn = connect()
    try:
        for statement in SCHEMA.split(";"):
            sql = statement.strip()
            if sql:
                conn.execute(sql)
        existing = conn.execute("SELECT COUNT(*) AS n FROM spl_portal.chats").fetchone()["n"]
        if existing == 0:
            _seed(conn)
        init_academy(conn)
        conn.commit()
    finally:
        conn.close()


